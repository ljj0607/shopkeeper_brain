from typing import Dict, List, Any
from FlagEmbedding import FlagReranker
import json

from knowledge.processor.query_process.base import BaseNode
from knowledge.processor.query_process.state import QueryGraphState
from knowledge.utils.client.ai_clients import AIClients

class RerankerNode(BaseNode):
    name = "reranker_node"

    def process(self, state: QueryGraphState) -> QueryGraphState:
        # 1、获取 query
        user_query = state.get("rewritten_query", '') or state.get("original_query", '')
        # 2、合并 rrf 和 mcp 两路结果
        rerank_inputs = self._collect_rerank_inputs(state)
        # 3、使用 ReRanker 进行精排
        reranked_docs = self._rerank(user_query, rerank_inputs)
        # 4、断崖检测算法
        cutoff_docs = self._cliff_cutoff(reranked_docs)

        state["reranked_docs"] = cutoff_docs
        return state

    def _collect_rerank_inputs(self, state: QueryGraphState) -> List[Dict[str, Any]]:
        results = []
        # 1、获取两路搜索结果
        rrf_chunks = state.get("rrf_chunks", [])
        web_search_docs = state.get("web_search_docs", [])

        # 2.遍历rrf_chunks，构建统一结构添加到results中
        for chunk in rrf_chunks:
            if not isinstance(chunk, dict):
                continue
            id = chunk.get("id", "")
            content = chunk.get("entity", {}).get("content", "")
            title = chunk.get("entity", {}).get("title", "")
            results.append({
                "id": id,
                "content": content,
                "title": title,
                "url": None,
                "source":"local"
            })

        # 3.遍历web_search_docs，构建统一结构添加到results中
        for doc in web_search_docs:
            if not isinstance(doc, dict):
                continue
            snippet = doc.get("snippet", "")
            title = doc.get("title", "")
            url = doc.get("url", "")

            results.append({
                "id": None,
                "content": snippet,
                "title": title,
                "url": url,
                "source":"web"
            })

        return results

    def _rerank(self, user_query: str, rerank_inputs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        # 1、获取 BGE Reranker 客户端
        try:
            rerank_client: FlagReranker = AIClients.get_bge_rerank_client()
        except Exception as e:
            self.logger.info("无法连接BGE Reranker服务: %s", e)
            return []

        # 2、构建 Q-D
        sentence_pairs = [(user_query, doc.get("content")) for doc in rerank_inputs]
        # 3、使用 BGE Reranker 进行精排
        scores = rerank_client.compute_score(sentence_pairs)
        # 4、将评分结果注入到 doc 中
        reranked_docs = [{ **doc, "score": scores[i]} for i, doc in enumerate(rerank_inputs)]
        # 5、按评分排序
        reranked_docs = sorted(reranked_docs, key=lambda x: x["score"], reverse=True)
        return reranked_docs

    def _cliff_cutoff(self, reranked_docs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        # 归一化得分
        scores = [doc.get("score") for doc in reranked_docs]
        normalized_scores = self._normalize_scores(scores)

        # 获取断崖位置
        max_bound = min(len(reranked_docs), self.config.rerank_max_top_k)
        max_gap = 0
        cutoff_pos = 0
        for i in range(max_bound - 1):
            current_score = normalized_scores[i]
            next_score = normalized_scores[i+1]
            gap = current_score - next_score

            if gap >= 0.15 and gap > max_gap:
                max_gap = gap
                cutoff_pos = i + 1

        # 设置下边界
        cutoff_pos = max(cutoff_pos, self.config.rerank_min_top_k)
        # 截断
        cuto_docs = reranked_docs[:cutoff_pos]
        return cuto_docs

    def _normalize_scores(self, scores:List[float]):
        """ 归一化得分 """
        min_score = min(scores)
        max_score = max(scores)
        normalized_scores = []

        for score in scores:
            # 归一化得分 = （当前分数-最小分数）/ (最大分数-最小分数)
            normalized_score = (score-max_score) / (max_score-min_score) if max_score != min_score else 0
            normalized_scores.append(normalized_score)

        return  normalized_scores






            





